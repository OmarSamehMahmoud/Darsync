-- Darsync hosted-platform foundation.
-- Apply in the Supabase SQL Editor before deploying the frontend.
-- Roles are never accepted from client signup metadata; new users are always "user".

create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique,
  role text not null default 'user' check (role in ('user','admin','super_admin')),
  permissions jsonb not null default '{"update_rag":false,"add_rag":false,"remove_rag":false}'::jsonb,
  created_at timestamptz not null default now()
);

-- Serialize signup attempts so simultaneous registrations cannot exceed five accounts.
create or replace function public.enforce_darsync_account_limit()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  account_count integer;
begin
  perform pg_catalog.pg_advisory_xact_lock(20261105, 5);
  select count(*) into account_count from auth.users;
  if account_count >= 5 then
    raise exception 'DARSYNC_ACCOUNT_LIMIT_REACHED'
      using errcode = 'check_violation';
  end if;
  return new;
end;
$$;

drop trigger if exists darsync_five_account_limit on auth.users;
create trigger darsync_five_account_limit
before insert on auth.users
for each row execute function public.enforce_darsync_account_limit();

create or replace function public.create_darsync_profile()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  requested_username text;
begin
  requested_username := coalesce(
    nullif(pg_catalog.btrim(new.raw_user_meta_data ->> 'username'), ''),
    split_part(coalesce(new.email, new.phone, new.id::text), '@', 1)
  );
  insert into public.profiles (id, username, role)
  values (new.id, requested_username, 'user');
  return new;
end;
$$;

drop trigger if exists darsync_create_profile on auth.users;
create trigger darsync_create_profile
after insert on auth.users
for each row execute function public.create_darsync_profile();

create or replace function public.is_darsync_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = (select auth.uid())
      and p.role in ('admin','super_admin')
  );
$$;

create table if not exists public.taxonomy (
  id bigint generated by default as identity primary key,
  type text not null check (type in ('country','category','subcategory','test')),
  name text not null,
  created_at timestamptz not null default now(),
  unique(type, name)
);

create table if not exists public.app_settings (
  key text primary key,
  value jsonb not null
);

create table if not exists public.study_files (
  id uuid primary key default gen_random_uuid(),
  filename text not null,
  storage_path text not null unique,
  size bigint not null check (size >= 0),
  country text,
  category text,
  subcategory text,
  test text,
  uploaded_by uuid references public.profiles(id) on delete set null,
  clauses integer not null default 0,
  ingested boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.chats (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  country text,
  category text,
  subcategory text,
  test text,
  title text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.messages (
  id uuid primary key default gen_random_uuid(),
  chat_id uuid not null references public.chats(id) on delete cascade,
  role text not null check (role in ('user','assistant')),
  content text not null,
  sources jsonb,
  qa jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.corrections (
  id uuid primary key default gen_random_uuid(),
  text text not null,
  scope jsonb,
  source text,
  active boolean not null default true,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.feedback (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  username text not null,
  type text not null default 'suggestion' check (type in ('feedback','suggestion')),
  title text,
  message text not null,
  admin_reply text,
  read_at timestamptz,
  replied_at timestamptz,
  deleted_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.study_documents (
  doc_id text primary key,
  generation_id text not null
);

create table if not exists public.study_pages (
  id bigint generated by default as identity primary key,
  doc_id text not null,
  generation_id text not null,
  file_id uuid not null references public.study_files(id) on delete cascade,
  page integer not null,
  part integer not null,
  number text not null,
  title text not null,
  source_file text not null,
  country text not null,
  category text not null,
  subcategory text not null,
  test text not null,
  text text not null,
  region_json jsonb not null default '[]'::jsonb,
  search_text text not null default '',
  unique(generation_id, page, part)
);

create table if not exists public.study_index_jobs (
  id uuid primary key default gen_random_uuid(),
  file_id uuid not null references public.study_files(id) on delete cascade,
  status text not null check (status in ('queued','running','completed','failed')),
  pages_processed integer not null default 0,
  pages_total integer not null default 0,
  error text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_study_pages_scope
  on public.study_pages(country, category, subcategory, test, generation_id);
create index if not exists idx_study_pages_file on public.study_pages(file_id);
create index if not exists idx_chats_user on public.chats(user_id);
create index if not exists idx_messages_chat on public.messages(chat_id);
create index if not exists idx_feedback_user on public.feedback(user_id);

-- Arabic-aware lexical search replaces SQLite FTS5 in the hosted database.
create index if not exists idx_study_pages_search
  on public.study_pages using gin (to_tsvector('simple', coalesce(search_text,'')));

